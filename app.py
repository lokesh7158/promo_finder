def _overview() -> None:
    _page_header("Overview dashboard", "Live metrics from the current execution only.")
    metrics = _run_summary()
    if not metrics:
        _show_empty_state("No current execution yet. Historical results are kept on a separate page.")
        return
    summary = metrics["evaluation_summary"]
    classifications = metrics["classification_distribution"]
    top_metrics = [
        ("Uploaded episodes", metrics["uploaded_episodes"]),
        ("Parsed successfully", metrics["parsed_episodes"]),
        ("Scenes", metrics["scenes"]),
        ("Timestamped events", metrics["events"]),
    ]
    next_metrics = [
        ("Candidates", metrics["candidates"]),
        ("Promo proposals", metrics["proposals"]),
        ("Evaluations", metrics["evaluations"]),
        ("Run status", metrics["status"].title()),
    ]
    columns = st.columns(4)
    for column, (label, value) in zip(columns, top_metrics, strict=True):
        column.metric(label, f"{value:,}" if isinstance(value, int) else value)
    columns = st.columns(4)
    for column, (label, value) in zip(columns, next_metrics, strict=True):
        column.metric(label, f"{value:,}" if isinstance(value, int) else value)

    durations = metrics.get("stage_seconds", {})
    total = sum(durations.values())
    st.markdown(f"**Processing duration:** {total:.2f} seconds")
    st.markdown("#### Evaluation classifications")
    if classifications:
        columns = st.columns(4)
        for column, name in zip(columns, ("STRONG", "PROMISING", "WEAK", "REJECT"), strict=True):
            column.metric(name.title(), classifications.get(name, 0))
    else:
        st.caption("No model scores were generated in this execution.")
    if summary.get("status") == "dry_run":
        st.caption("Evaluation selected: offline structural validation only; no scores or API calls.")
    if metrics.get("logs"):
        with st.expander("Execution status"):
            for entry in metrics["logs"]:
                st.write(entry)


def _upload_and_run() -> None:
    _page_header("Upload & processing", "Validate screenplay files, select stages, then explicitly run.")
    _llm_configuration()
    st.divider()
    st.caption(f"Up to {MAX_EPISODES} UTF-8 TXT files. Processing does not start on page refresh.")
    if DEMO_MODE:
        st.download_button(
            "Download 50-file synthetic sample pack",
            data=synthetic_pack_zip(),
            file_name="promofinder_synthetic_demo_50.zip",
            mime="application/zip",
            help="All contents are newly generated synthetic text; no assignment screenplay is included.",
        )

    upload_key = f"screenplay_upload_{st.session_state['upload_widget_version']}"
    uploads = st.file_uploader(
        "Screenplay TXT files",
        type=["txt"],
        accept_multiple_files=True,
        key=upload_key,
        help="Select up to 50 files. Empty, duplicate, non-UTF-8, and invalid files are rejected.",
    )
    content = [(upload.name, upload.getvalue()) for upload in uploads or []]
    valid, errors, warnings = validate_uploads(content, demo_mode=DEMO_MODE)
    st.markdown("#### Uploaded files")
    if content:
        rows = []
        for name, file_content in content:
            file_errors = [
                error for error in errors
                if error.startswith(f"{name}:")
                or f"filenames are not allowed: {name}" in error
                or (len(content) > MAX_EPISODES and "at most" in error)
                or "Combined upload exceeds" in error
            ]
            rows.append(
                {
                    "Filename": name,
                    "Size (bytes)": len(file_content),
                    "Type": Path(name).suffix.lower(),
                    "Validation": "Rejected" if file_errors else "Valid",
                }
            )
        st.dataframe(rows, width="stretch", hide_index=True)
    else:
        st.caption("No files selected.")
    if content:
        for warning in warnings:
            st.warning(warning)
        if errors:
            for error in errors:
                st.error(error)
    if st.session_state.get("run_notice"):
        st.success(st.session_state.pop("run_notice"))

    selected_stages = st.multiselect(
        "Pipeline stages",
        options=list(STAGES),
        default=list(STAGES),
        help="Required upstream stages are automatically included.",
    )
    if "Evaluation" in selected_stages:
        st.caption(
            "The pipeline button performs offline evaluation-input validation only. "
            "Live provider requests require the separate Run LLM Evaluation action above."
        )
    submit = st.button(
        "Run pipeline",
        type="primary",
        width="stretch",
        disabled=not valid or bool(errors) or not selected_stages,
    )
    if not submit:
        return

    try:
        resolved_stages = normalize_stages(selected_stages)
    except ValueError as error:
        st.error(str(error))
        return
    added = [stage for stage in resolved_stages if stage not in selected_stages]
    if added:
        st.info("Prerequisite stages added automatically: " + ", ".join(added))
    progress_bar = st.progress(0, text="Preparing temporary run workspace...")
    status = st.empty()
    stage_counter = {"value": 0}

    def update_progress(message: str) -> None:
        stage_counter["value"] += 1
        fraction = min(stage_counter["value"] / max(1, len(resolved_stages) * 2), 0.95)
        progress_bar.progress(fraction, text=message)
        status.caption(message)

    try:
        workspace = run_pipeline(
            valid,
            selected_stages=resolved_stages,
            run_gemini=False,
            progress=update_progress,
        )
        try:
            metrics = run_metrics(workspace)
        except Exception:
            workspace.cleanup()
            raise
        previous_workspace = st.session_state.get("current_workspace")
        st.session_state["current_workspace"] = workspace
        st.session_state["current_metrics"] = metrics
        if previous_workspace is not None:
            previous_workspace.cleanup()
        st.session_state["run_notice"] = "Execution completed. Open the dashboard pages to inspect its results."
        st.session_state["upload_widget_version"] += 1
        st.rerun()
    except Exception as error:
        progress_bar.empty()
        st.error(f"Pipeline execution stopped safely: {error}")


def _display_rows(metrics: dict[str, Any]) -> list[dict[str, Any]]:
    displayed = []
    for item in ranked_records(metrics):
        segments = item.get("segments", [])
        evaluation = item.get("evaluation", {})
        episode_numbers = sorted(
            {
                segment.get("episode_number")
                for segment in segments
                if isinstance(segment, dict) and segment.get("episode_number") is not None
            }
        )
        displayed.append(
            {
                "Rank": item.get("rank"),
                "Shortlist rank": item.get("shortlist_rank"),
                "Promo ID": item.get("promo_id"),
                "Episode": ", ".join(map(str, episode_numbers)),
                "Promo type": item.get("promo_category"),
                "Duration (s)": item.get("total_duration_seconds"),
                "Score": evaluation.get("final_score"),
                "Classification": evaluation.get("classification"),
                "Human review": (
                    "Required"
                    if evaluation.get("human_review_required") is True
                    else "Not evaluated"
                    if not evaluation
                    else "Not flagged"
                ),
            }
        )
    return displayed


def _promo_discovery() -> None:
    _page_header("Promo discovery", "Search, filter, sort, and inspect source-traceable proposals.")
    metrics = _run_summary()
    if not metrics:
        _show_empty_state("Run a pipeline with promo proposal generation to explore proposals.")
        return
    rows = _display_rows(metrics)
    if not rows:
        _show_empty_state("This execution did not generate any promo proposals.")
        return
    if metrics["evaluations"] == 0:
        st.info("Showing the proposal-generator shortlist order. No evaluation scores or score-based ranking exist for this run.")

    col1, col2, col3 = st.columns([2, 1, 1])
    query = col1.text_input("Search promo ID or episode", placeholder="Search...")
    categories = sorted({row["Promo type"] for row in rows if row["Promo type"]})
    selected_categories = col2.multiselect("Promo type", categories, default=categories)
    classifications = sorted({row["Classification"] for row in rows if row["Classification"]})
    selected_classifications = col3.multiselect(
        "Classification", classifications, default=classifications
    )
    episode_values = sorted(
        {
            episode
            for row in rows
            for episode in row["Episode"].split(", ")
            if episode
        }
    )
    selected_episodes = st.multiselect("Episode", episode_values, default=episode_values)
    duration_values = [float(row["Duration (s)"] or 0) for row in rows]
    if min(duration_values) == max(duration_values):
        duration_range = (min(duration_values), max(duration_values))
        st.caption(f"All matching proposals are {duration_range[0]:g} seconds.")
    else:
        duration_range = st.slider(
            "Duration range (seconds)",
            min_value=float(min(duration_values)),
            max_value=float(max(duration_values)),
            value=(float(min(duration_values)), float(max(duration_values))),
        )
    available_scores = [float(row["Score"]) for row in rows if row["Score"] is not None]
    score_range: tuple[float, float] | None = None
    if available_scores:
        if min(available_scores) == max(available_scores):
            score_range = (min(available_scores), max(available_scores))
            st.caption(f"All evaluated proposals scored {score_range[0]:g}.")
        else:
            score_range = st.slider(
                "Evaluation score range",
                min_value=min(available_scores),
                max_value=max(available_scores),
                value=(min(available_scores), max(available_scores)),
            )

    filtered = []
    for row in rows:
        episode_match = any(ep in selected_episodes for ep in row["Episode"].split(", ") if ep)
        search_match = not query or query.casefold() in (
            str(row["Promo ID"]) + " " + row["Episode"]
        ).casefold()
        score = row["Score"]
        score_match = score_range is None or (
            score is not None and score_range[0] <= float(score) <= score_range[1]
        )
        classification_match = (
            not classifications or row["Classification"] in selected_classifications
        )
        if (
            search_match
            and episode_match
            and row["Promo type"] in selected_categories
            and classification_match
            and duration_range[0] <= float(row["Duration (s)"] or 0) <= duration_range[1]
            and score_match
        ):
            filtered.append(row)

    page_size = st.selectbox("Rows per page", [10, 25, 50, 100], index=1)
    page_count = max(1, (len(filtered) + page_size - 1) // page_size)
    page = st.number_input("Page", min_value=1, max_value=page_count, value=1, step=1)
    start = (int(page) - 1) * page_size
    st.caption(f"Showing {len(filtered):,} matching promos; page {page} of {page_count}.")
    st.dataframe(filtered[start : start + page_size], width="stretch", hide_index=True)

    by_id = {item.get("promo_id"): item for item in metrics["results"]}
    choices = [item["Promo ID"] for item in filtered]
    if not choices:
        st.warning("No promos match the selected filters.")
        return
    selected_id = st.selectbox("Inspect a promo", choices)
    _promo_detail(by_id[selected_id])


def _promo_detail(item: dict[str, Any]) -> None:
    evaluation = item.get("evaluation", {})
    segments = sorted(
        item.get("segments", []),
        key=lambda segment: segment.get("segment_order", segment.get("playback_order", 0)),
    )
    st.markdown("### Promo detail")
    st.write(f"**Promo ID:** `{item.get('promo_id')}`")
    st.write(f"**Category:** {item.get('promo_category', 'Unknown')}")
    st.write(f"**Total duration:** {item.get('total_duration_seconds', 'Unknown')} seconds")
    validation_status = item.get("validation_status")
    if validation_status:
        st.markdown("**Structural validation status**")
        if isinstance(validation_status, dict):
            st.json(validation_status, expanded=False)
        else:
            st.text(str(validation_status))
    if evaluation:
        st.write(
            f"**Evaluation:** {evaluation.get('final_score', 'N/A')} / 100 · "
            f"{evaluation.get('classification', 'Unclassified')} · "
            f"Human review: {'required' if evaluation.get('human_review_required') else 'not flagged'}"
        )
        hook = evaluation.get("hook", {})
        cliffhanger = evaluation.get("cliffhanger", {})
        st.markdown("**Hook**")
        st.text(hook.get("description", "Not provided"))
        st.markdown("**Cliffhanger**")
        st.text(cliffhanger.get("description", "Not provided"))
        if evaluation.get("scores"):
            st.json(evaluation["scores"], expanded=False)
        explanation = (
            evaluation.get("explanation")
            or evaluation.get("rationale")
            or item.get("explanation")
        )
        if explanation:
            st.markdown("#### Explanation")
            st.text(explanation)
    else:
        st.caption("Not evaluated. Model-generated descriptions, scores, and classifications are unavailable.")

    for index, segment in enumerate(segments, start=1):
        order = segment.get("segment_order", segment.get("playback_order", index))
        with st.expander(
            f"Playback segment {order} · Episode {segment.get('episode_number', '?')} · "
            f"{segment.get('start_timestamp', segment.get('source_start_timestamp', '?'))}–"
            f"{segment.get('end_timestamp', segment.get('source_end_timestamp', '?'))}"
        ):
            st.write(f"**Playback offset:** {segment.get('playback_offset_seconds', 'Not provided')}")
            st.write(f"**Playback end:** {segment.get('playback_end_seconds', 'Not provided')}")
            st.write(f"**Source episode:** {segment.get('episode_id', 'Unknown')}")
            for event_record in segment.get("events", []):
                event = event_record.get("event", event_record)
                start = event.get("start", {}).get("raw")
                end = event.get("end", {}).get("raw")
                content = event.get("content", {}).get("raw", "")
                st.markdown(f"**{event.get('type', 'EVENT')}** `{start}–{end}`")
                st.text(content)
    if evaluation:
        evidence = []
        for claim_name in ("hook", "cliffhanger"):
            for record in evaluation.get(claim_name, {}).get("evidence", []):
                evidence.append(
                    {
                        "claim": claim_name,
                        "segment": record.get("segment_id"),
                        "playback_order": record.get("playback_order"),
                        "episode": record.get("episode_id"),
                        "event": record.get("event_id"),
                        "source_timestamp": record.get("source_timestamp"),
                        "playback_timestamp": record.get("playback_timestamp"),
                        "excerpt": record.get("excerpt"),
                    }
                )
        if evidence:
            st.markdown("#### Evidence references")
            st.dataframe(evidence, width="stretch", hide_index=True)
        warnings = item.get("rejection_reasons", [])
        uncertainties = evaluation.get("uncertainties", [])
        validation_warnings = evaluation.get("validation_warnings", [])
        if warnings or uncertainties or validation_warnings:
            st.markdown("#### Validation warnings and model uncertainties")
            for warning in warnings:
                st.warning(str(warning))
            for warning in validation_warnings:
                st.warning(str(warning))
            for uncertainty in uncertainties:
                st.write(f"- {uncertainty}")
    st.caption("Screenplay timestamps are source references, not footage-verified cut points.")


def _analytics() -> None:
    _page_header("Analytics", "Interactive visualizations derived from this execution's output files.")
    metrics = _run_summary()
    if not metrics:
        _show_empty_state("Run a pipeline to build charts from its actual outputs.")
        return
    episodes = metrics.get("episodes", [])
    results = metrics.get("results", [])
    promo_types = sorted(
        {
            str(result.get("promo_category"))
            for result in results
            if result.get("promo_category")
        }
    )
    selected_types = st.multiselect(
        "Promo types",
        promo_types,
        default=promo_types,
        key="analytics_promo_types",
    )
    if promo_types:
        results = [
            result for result in results if result.get("promo_category") in selected_types
        ]
    episode_values = sorted(
        {str(episode.get("episode")) for episode in episodes if episode.get("episode") is not None}
    )
    selected_episode_values = st.multiselect(
        "Episodes",
        episode_values,
        default=episode_values,
        key="analytics_episodes",
    )
    filtered_episodes = [
        episode
        for episode in episodes
        if str(episode.get("episode")) in selected_episode_values
    ]
    col1, col2 = st.columns(2)
    if filtered_episodes:
        episode_frame = [
            {"Episode": row["episode"], "Candidates": row["candidate_count"]}
            for row in filtered_episodes
        ]
        col1.plotly_chart(
            px.bar(
                episode_frame,
                x="Episode",
                y="Candidates",
                title="Candidates per episode",
                hover_data=["Candidates"],
            ),
            width="stretch",
        )
        proposal_frame = [
            {"Episode": row["episode"], "Proposals": row["proposal_count"]}
            for row in filtered_episodes
        ]
        col2.plotly_chart(
            px.bar(
                proposal_frame,
                x="Episode",
                y="Proposals",
                title="Proposals involving each episode",
                hover_data=["Proposals"],
            ),
            width="stretch",
        )
    else:
        col1.info("No episodes match the selected episode filter.")
        col2.info("No episodes match the selected episode filter.")

    durations = [
        {"Duration (seconds)": row.get("total_duration_seconds"), "Promo type": row.get("promo_category")}
        for row in results
        if isinstance(row.get("total_duration_seconds"), (int, float))
    ]
    categories = [
        {"Promo type": row.get("promo_category", "Unknown")}
        for row in results
    ]
    col1, col2 = st.columns(2)
    if durations:
        col1.plotly_chart(
            px.histogram(durations, x="Duration (seconds)", color="Promo type", nbins=20,
                         title="Promo duration distribution"),
            width="stretch",
        )
    else:
        col1.info("No promo durations available.")
    if categories:
        counts = Counter(row["Promo type"] for row in categories)
        col2.plotly_chart(
            px.pie(
                [{"Promo type": key, "Count": value} for key, value in counts.items()],
                names="Promo type", values="Count", title="Promo type distribution",
            ),
            width="stretch",
        )
    else:
        col2.info("No promo categories available.")

    scored = [
        {
            "Score": row["evaluation"].get("final_score"),
            "Classification": row["evaluation"].get("classification"),
            "Promo type": row.get("promo_category"),
        }
        for row in results
        if isinstance(row.get("evaluation"), dict)
        and isinstance(row["evaluation"].get("final_score"), (int, float))
    ]
    col1, col2 = st.columns(2)
    if scored:
        col1.plotly_chart(
            px.histogram(scored, x="Score", color="Classification", nbins=20,
                         title="Evaluation score distribution"),
            width="stretch",
        )
        classification_counts = Counter(row["Classification"] for row in scored)
        col2.plotly_chart(
            px.pie(
                [{"Classification": key, "Count": value} for key, value in classification_counts.items()],
                names="Classification", values="Count", title="Strong / Promising / Weak / Reject",
            ),
            width="stretch",
        )
        st.plotly_chart(
            px.box(scored, x="Promo type", y="Score", color="Promo type",
                   title="Evaluation scores by promo type"),
            width="stretch",
        )
    else:
        col1.info("No evaluation scores exist for this execution.")
        col2.info("Classification charts appear after an explicit live evaluation.")

    if episodes:
        st.markdown("#### Episode-level processing statistics")
        st.dataframe(filtered_episodes, width="stretch", hide_index=True)
    if metrics.get("stage_seconds"):
        st.plotly_chart(
            px.bar(
                [{"Stage": stage, "Seconds": seconds}
                 for stage, seconds in metrics["stage_seconds"].items()],
                x="Stage", y="Seconds", title="Processing time by stage",
            ),
            width="stretch",
        )


def _historical() -> None:
    _page_header("Historical results", "Read-only local results, separate from current executions.")
    if DEMO_MODE:
        st.info("Historical data access is disabled in hosted demonstration mode.")
        return
    history = load_historical_results(demo_mode=False)
    if not history:
        st.info("No local historical result bundle was found.")
        return
    st.warning("Historical results are not part of the current execution and are never loaded in demo mode.")
    candidate_counts = history["candidate_summary"].get("counts", {})
    proposal_summary = history["proposal_summary"].get("summary", {})
    manifest = history["consolidated_manifest"]
    ranking = history["ranking"]
    values = [
        ("Episodes processed", candidate_counts.get("parsed_episode_files", 0)),
        ("Scenes", history["scene_count"]),
        ("Timestamped events", history["event_count"]),
        ("Candidates", candidate_counts.get("stage_b_candidates", 0)),
        ("Proposals", proposal_summary.get("proposal_count_before_validation", 0)),
        ("Valid proposals", proposal_summary.get("valid_proposal_count", 0)),
        ("Shortlist", proposal_summary.get("shortlist_count", 0)),
        ("Validated evaluations", manifest.get("validated_record_count", 0)),
        ("Unvalidated", manifest.get("unvalidated_count", 0)),
    ]
    for offset in range(0, len(values), 3):
        columns = st.columns(3)
        for column, (label, value) in zip(columns, values[offset : offset + 3]):
            column.metric(label, f"{value:,}" if isinstance(value, int) else value)
    st.caption(
        f"Historical ranking label: {ranking.get('ranking_label', 'not specified')}. "
        "All model scores remain model-generated and require human review."
    )
    records = ranking.get("ranked_proposals", [])
    if records:
        view = [
            {
                "Priority rank": item.get("ranking_analysis", {}).get("full_rank"),
                "Promo ID": item.get("proposal_id"),
                "Episodes": ", ".join(map(str, item.get("source_episode_numbers", []))),
                "Type": item.get("promo_category"),
                "Duration (s)": item.get("total_duration_seconds"),
                "Model score": item.get("model_final_score"),
                "Classification": item.get("model_classification"),
                "Human review": item.get("human_review_required"),
            }
            for item in records
        ]
        st.dataframe(view[:200], width="stretch", hide_index=True)
        st.caption(f"Showing first 200 of {len(records):,} historical records.")
    final_recommendations = history.get("final_recommendations", [])
    if final_recommendations:
        st.markdown("#### Existing final five recommendations")
        st.dataframe(final_recommendations, width="stretch", hide_index=True)
        st.caption(
            "Displayed from the existing repository documentation without altering recommendations "
            "or timestamps. These remain screenplay-based and require footage verification."
        )


def _export() -> None:
    _page_header("Export", "Download outputs for the current execution only.")
    metrics = _run_summary()
    workspace = st.session_state.get("current_workspace")
    if not metrics or workspace is None:
        _show_empty_state("There is no current execution to export.")
        return
    rows = ranked_records(metrics)
    output = workspace.root / "outputs"
    ranked_path = output / "proposal_evaluations" / "ranked_proposals.json"
    shortlist_path = output / "promo_proposals" / "shortlist.json"
    if ranked_path.is_file():
        st.download_button(
            "Download ranked promo results JSON",
            ranked_path.read_bytes(),
            "ranked_promo_results.json",
            "application/json",
        )
    elif shortlist_path.is_file():
        st.download_button(
            "Download proposal shortlist JSON (not a score ranking)",
            shortlist_path.read_bytes(),
            "promo_shortlist.json",
            "application/json",
        )
    else:
        st.info("This execution did not generate promo proposals to export.")
    if ranked_path.is_file() or shortlist_path.is_file():
        st.download_button(
            "Download promo results CSV",
            records_csv(rows),
            "promo_results.csv",
            "text/csv",
        )
    evaluation_summary = metrics.get("evaluation_summary") or {
        "status": "not_run",
        "validated_proposal_count": 0,
        "evaluations_are_real_model_outputs": False,
    }
    st.download_button(
        "Download evaluation summary JSON",
        json.dumps(evaluation_summary, indent=2, ensure_ascii=False).encode("utf-8"),
        "evaluation_summary.json",
        "application/json",
    )
    st.download_button(
        "Download analytics summary JSON",
        json.dumps(analytics_summary(metrics), indent=2, ensure_ascii=False).encode("utf-8"),
        "analytics_summary.json",
        "application/json",
    )
    if workspace.archive_bytes is None:
        with st.spinner("Packaging generated output files..."):
            workspace.archive_bytes = outputs_zip(workspace)
    st.download_button(
        "Download generated outputs ZIP",
        workspace.archive_bytes,
        "promofinder_generated_outputs.zip",
        "application/zip",
        help="Contains only generated stage outputs. The uploaded input directory is excluded.",
    )


def main() -> None:
    with st.sidebar:
        st.markdown("## PromoFinder AI")
        st.caption("Screenplay intelligence workspace")
        page = st.radio(
            "Navigation",
            ("Overview", "Upload & Run", "Promo Discovery", "Analytics", "Historical Results", "Export"),
            label_visibility="collapsed",
        )
        st.divider()
        st.markdown(f'<span class="status-pill">{MODE.upper()} MODE</span>', unsafe_allow_html=True)
        if st.button("Clear current run data", width="stretch"):
            _clear_current_run()
            session_id = _session_id()
            if session_id:
                clear_session_credentials(session_id)
            st.session_state["upload_widget_version"] += 1
            st.rerun()

    if page == "Overview":
        _hero()
        _overview()
    elif page == "Upload & Run":
        _upload_and_run()
    elif page == "Promo Discovery":
        _promo_discovery()
    elif page == "Analytics":
        _analytics()
    elif page == "Historical Results":
        _historical()
    else:
        _export()


if __name__ == "__main__":
    main()
