def _session_id() -> str | None:
    from streamlit.runtime.scriptrunner import get_script_run_ctx

    context = get_script_run_ctx(suppress_warning=True)
    return getattr(context, "session_id", None) if context else None


def _capture_api_key(*, force_save: bool = False) -> None:
    session_id = _session_id()
    api_key = st.session_state.pop("llm_api_key_input", "")
    provider_label = st.session_state.get("llm_provider")
    provider = _PROVIDERS.get(provider_label, (None, None))[0]
    if session_id and provider and api_key:
        store_credential(
            session_id,
            provider,
            api_key,
            save_for_session=force_save
            or bool(st.session_state.get("save_llm_key_for_session")),
        )


def _llm_configuration() -> None:
    st.markdown("#### LLM Configuration")
    if DEMO_MODE:
        st.info(
            "Live LLM evaluation is disabled in hosted synthetic-demo mode. "
            "No provider credentials are requested or accepted here."
        )
        return

    provider_label = st.selectbox(
        "Provider",
        tuple(_PROVIDERS),
        key="llm_provider",
    )
    provider, key_environment_name = _PROVIDERS[provider_label]
    presets = _MODEL_PRESETS[provider]
    model_choice = st.selectbox(
        "Model",
        (*presets, "Enter a custom model ID"),
        key=f"llm_model_choice_{provider}",
    )
    if model_choice == "Enter a custom model ID":
        model = st.text_input(
            "Custom model ID",
            key=f"llm_custom_model_{provider}",
            placeholder="Enter the exact model ID supported by the provider",
        ).strip()
    else:
        model = model_choice
    max_proposals = st.number_input(
        "Maximum proposals to evaluate",
        min_value=1,
        max_value=200,
        value=1,
        step=1,
    )
    authorized = st.checkbox(
        "I explicitly authorize sending the selected proposals and their source excerpts "
        "to this provider for evaluation.",
        value=False,
    )
    gemini_confirmed = False
    if provider == "gemini":
        gemini_confirmed = st.checkbox(
            "I confirm this Gemini request is for the existing verified free-tier model "
            "and project configuration.",
            value=False,
        )
    with st.form("llm_configuration_form", clear_on_submit=False):
        st.text_input(
            "Provider API key",
            type="password",
            key="llm_api_key_input",
            help=(
                "The key is never displayed. Submitted values are moved to a "
                "short-lived server-memory store and removed from Streamlit widget state."
            ),
        )
        st.checkbox(
            "Save for this session (server memory; expires after 20 minutes idle)",
            key="save_llm_key_for_session",
            value=False,
        )
        button_columns = st.columns(3)
        test_clicked = button_columns[0].form_submit_button(
            "Test Connection",
            on_click=_capture_api_key,
        )
        save_clicked = button_columns[1].form_submit_button(
            "Save Key for Session",
            on_click=_capture_api_key,
            kwargs={"force_save": True},
        )
        run_clicked = button_columns[2].form_submit_button(
            "Run LLM Evaluation",
            type="primary",
            on_click=_capture_api_key,
        )

    session_id = _session_id()
    if session_id and has_saved_credential(session_id, provider):
        if st.button("Forget saved key for this provider", key=f"clear_llm_key_{provider}"):
            clear_credential(session_id, provider)
            st.success("The saved provider key was removed from server memory.")
    if save_clicked:
        if session_id and has_saved_credential(session_id, provider):
            st.success(f"{provider_label} key saved in server memory for this session.")
        else:
            st.error("Enter an API key before saving it for this session.")
        return

    if not (test_clicked or run_clicked):
        if session_id and has_saved_credential(session_id, provider):
            st.caption(f"A {provider_label} key is saved in server memory for this session.")
        elif _secret(key_environment_name):
            st.caption(f"A {provider_label} key is configured in the local environment/secrets.")
        return

    if not model:
        st.error("Enter a model ID before testing the connection or evaluating proposals.")
        return
    api_key = (
        credential_for_action(session_id, provider)
        if session_id
        else None
    ) or _secret(key_environment_name)
    if not api_key:
        st.error(f"Enter a {provider_label} API key or configure {key_environment_name} locally.")
        return
    if provider == "gemini" and not gemini_confirmed:
        st.error("Explicit free-tier confirmation is required for every Gemini action.")
        return
    config = LLMConfig(
        provider=provider,
        model=model,
        api_key=api_key,
        batch_size=1,
        max_retries=2,
        timeout_seconds=60,
        free_tier_confirmed=gemini_confirmed,
    )
    if test_clicked:
        try:
            connection = create_provider(config).test_connection()
        except (LLMClientError, ValueError) as error:
            st.error(str(error))
        else:
            st.success(
                f"Connection verified: {provider_label} / {connection.get('model', model)}."
            )
        return

    if not authorized:
        st.error(
            "Confirm that you authorize the selected provider to process proposal excerpts."
        )
        return
    workspace = st.session_state.get("current_workspace")
    if workspace is None:
        st.error("Run the pipeline and generate a proposal shortlist before live evaluation.")
        return
    progress_bar = st.progress(0, text="Preparing the bounded evaluation...")
    status = st.empty()

    def update_evaluation_progress(done: int, total: int, promo_id: str) -> None:
        progress_bar.progress(
            min(done / max(total, 1), 1.0),
            text=f"Evaluating proposal {done} of {total}: {promo_id}",
        )
        status.caption(f"Provider: {provider_label} | Model: {model}")

    try:
        result = run_live_evaluation(
            workspace,
            config=config,
            limit=int(max_proposals),
            progress=update_evaluation_progress,
        )
        metrics = run_metrics(workspace)
        st.session_state["current_metrics"] = metrics
        usage = provider_usage_summary(workspace, provider=provider)
        result_message = (
            f"{provider_label} / {model}: {result['validated']} validated, "
            f"{result['failed']} failed, {result['skipped_resumed']} already complete."
        )
        if result["failed"] or result["stopped_for_quota"]:
            st.warning(result_message)
        else:
            st.success(result_message)
        if result["stopped_for_quota"]:
            st.warning("The provider rate/quota safeguard stopped further requests.")
        if usage["reported_token_counts"]:
            st.caption(f"Provider-reported token usage: {usage['reported_token_counts']}")
        st.caption(
            "Cost estimate unavailable: provider pricing depends on account, model, "
            "and current rates. Check your provider console."
        )
        failure_path = (
            workspace.root
            / "outputs"
            / "proposal_evaluations"
            / "failed_proposals.json"
        )
        if failure_path.is_file():
            failures = json.loads(failure_path.read_text(encoding="utf-8")).get(
                "failures", []
            )
            if failures:
                st.dataframe(
                    [
                        {
                            "Promo ID": item.get("promo_id"),
                            "Failure type": item.get("error_type"),
                            "Details": item.get("message"),
                        }
                        for item in failures[:10]
                    ],
                    width="stretch",
                    hide_index=True,
                )
    except (LLMClientError, LLMQuotaExceededError, ValueError, OSError) as error:
        st.error(f"Live evaluation stopped safely: {error}")


