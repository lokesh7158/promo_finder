def _secret(name: str) -> str | None:
    value = os.getenv(name)
    if value:
        return value
    try:
        value = st.secrets.get(name)
    except StreamlitSecretNotFoundError:
        value = None
    return str(value) if value else None


def _application_mode() -> str:
    if (_secret("PROMOFINDER_HOSTED") or "").strip() == "1":
        return "demo"

    # Demo is the safe default; the public UI never offers a mode switch.
    try:
        configured = st.secrets.get("PROMOFINDER_MODE")
    except StreamlitSecretNotFoundError:
        configured = None
    configured = configured or os.getenv("PROMOFINDER_MODE")
    return "local" if configured and configured.strip().lower() == "local" else "demo"


